    def test_postgres_read_connection_sets_session_default_read_only(self):
        class FakeError(Exception):
            pass

        class RawConnection:
            def __init__(self):
                self.statements = []
                self.commits = 0

            def execute(self, statement, params=None):
                self.statements.append((statement, params))
                return self

            def commit(self):
                self.commits += 1

            def close(self):
                pass

        raw = RawConnection()

        class FakePsycopg:
            Error = FakeError

            @staticmethod
            def connect(url, *, autocommit, row_factory):
                self.assertEqual(url, "postgresql://fixture.invalid/topik")
                self.assertFalse(autocommit)
                return raw

        with patch.object(database, "_psycopg", return_value=(FakePsycopg, object())):
            connection = database.connect_postgres(
                "postgresql://fixture.invalid/topik", readonly=True
            )
        self.assertIs(connection, raw)
        self.assertEqual(raw.statements, [("SET default_transaction_read_only = on", None)])
        self.assertEqual(raw.commits, 1)

    def test_sqlite_readonly_rejects_writes(self):
        with tempfile.TemporaryDirectory(prefix="topik-readonly-") as tmp:
            path = Path(tmp) / "test.sqlite"
            with closing(sqlite3.connect(path)) as db:
                db.execute("CREATE TABLE sample(id INTEGER PRIMARY KEY, value TEXT)")
                db.execute("INSERT INTO sample(value) VALUES('unchanged')")
                db.commit()
            before = hashlib.sha256(path.read_bytes()).hexdigest()
            with database.sqlite_readonly(path) as db:
                self.assertTrue(db.in_transaction)
                self.assertEqual(db.execute("SELECT value FROM sample").fetchone()[0], "unchanged")
                with self.assertRaises(sqlite3.OperationalError):
                    db.execute("UPDATE sample SET value='changed'")
            self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(), before)

