    @unittest.skipUnless(REAL_DB.is_file(), "Private 35-I SQLite database is not installed")
    def test_migration_rolls_back_target_transaction_on_insert_failure(self):
        class Result:
            def fetchone(self):
                return {"count": 0}

            def fetchall(self):
                return []

        class Cursor:
            def __enter__(self):
                return self

            def __exit__(self, exc_type, exc, tb):
                return False

            def executemany(self, statement, rows):
                raise RuntimeError("simulated PostgreSQL insert failure")

        class FakePostgres:
            def __init__(self):
                self.committed = False
                self.rolled_back = False

            def execute(self, statement, params=None):
                if "information_schema.tables" in statement:
                    return Result()
                if statement.lstrip().upper().startswith("SELECT COUNT(*) AS COUNT FROM"):
                    return Result()
                return Result()

            def cursor(self):
                return Cursor()

            def commit(self):
                self.committed = True

            def rollback(self):
                self.rolled_back = True

        pg = FakePostgres()

        @contextmanager
        def fake_connection(_url):
            yield pg

        before = hashlib.sha256(REAL_DB.read_bytes()).hexdigest()
        with patch.object(migration, "get_database_url", return_value="postgresql://test.invalid/topik"), \
             patch.object(migration, "postgres_connection", side_effect=fake_connection), \
             patch.object(migration, "validate_postgres_structure", return_value=[]):
            with self.assertRaisesRegex(RuntimeError, "simulated PostgreSQL insert failure"):
                migration.migrate(REAL_DB, require_baseline=True)
        self.assertTrue(pg.rolled_back)
        self.assertFalse(pg.committed)
        self.assertEqual(hashlib.sha256(REAL_DB.read_bytes()).hexdigest(), before)


